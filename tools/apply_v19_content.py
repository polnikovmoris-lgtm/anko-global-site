def main() -> None:
    changed = []
    for filename, snippet in SNIPPETS.items():
        path = SITE / filename
        text = path.read_text(encoding="utf-8")

        for old, new in REPLACEMENTS.get(filename, {}).items():
            if old in text:
                text = text.replace(old, new, 1)
            elif new not in text:
                raise RuntimeError(f"Replacement anchor not found in {filename}")

        heading = snippet.split("<h2>", 1)[1].split("</h2>", 1)[0]
        if heading in text:
            path.write_text(text, encoding="utf-8")
            continue
        else:
            text, count = INSERT_PATTERN.subn(
                snippet + '    </div>\n\n    <div class="usps">', text, count=1
            )
            if count != 1:
                raise RuntimeError(f"Unexpected content marker count in {filename}")
        path.write_text(text, encoding="utf-8")
        changed.append(filename)

    print(f"Updated {len(changed)} product pages")
    for filename in changed:
        print(filename)


if __name__ == "__main__":
    main()
